-- Supabase schema for the Asmak Albaraka customer booking portal.
-- Safe to run in SQL Editor. Never put service_role keys in client apps.

create extension if not exists pgcrypto;

create table if not exists public.cloud_fish_products (
  id bigint generated by default as identity primary key,
  name text not null check (length(trim(name)) between 1 and 120),
  description text not null default '',
  image_url text,
  price_per_kg numeric(12,2) not null check (price_per_kg >= 0),
  is_active boolean not null default true,
  is_offer boolean not null default false,
  offer_price_per_kg numeric(12,2) check (offer_price_per_kg is null or offer_price_per_kg >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint offer_price_valid check (not is_offer or offer_price_per_kg is not null)
);

create table if not exists public.customer_orders (
  id uuid primary key default gen_random_uuid(),
  order_code text not null unique default upper(substr(encode(gen_random_bytes(8),'hex'),1,10)),
  customer_name text not null check (length(trim(customer_name)) between 2 and 120),
  customer_phone text not null check (length(trim(customer_phone)) between 7 and 30),
  pickup_at timestamptz not null,
  notes text not null default '',
  status text not null default 'جديد'
    check (status in ('جديد','مؤكد','قيد التجهيز','جاهز للاستلام','تم التسليم','ملغي')),
  total numeric(12,2) not null default 0 check (total >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.customer_order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.customer_orders(id) on delete cascade,
  product_id bigint not null references public.cloud_fish_products(id),
  fish_name text not null,
  quantity_kg numeric(12,3) not null check (quantity_kg > 0 and quantity_kg <= 100),
  unit_price numeric(12,2) not null check (unit_price >= 0),
  line_total numeric(12,2) not null check (line_total >= 0)
);

-- Admin membership is assigned manually to a verified Supabase Auth user.
create table if not exists public.store_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create or replace function public.is_store_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.store_admins
    where user_id = (select auth.uid())
  );
$$;

alter table public.cloud_fish_products enable row level security;
alter table public.customer_orders enable row level security;
alter table public.customer_order_items enable row level security;
alter table public.store_admins enable row level security;

drop policy if exists "Public can view active fish products" on public.cloud_fish_products;
create policy "Public can view active fish products"
on public.cloud_fish_products for select to anon, authenticated
using (is_active = true or (select public.is_store_admin()));

drop policy if exists "Admins manage fish products" on public.cloud_fish_products;
create policy "Admins manage fish products"
on public.cloud_fish_products for all to authenticated
using ((select public.is_store_admin()))
with check ((select public.is_store_admin()));

drop policy if exists "Admins read customer orders" on public.customer_orders;
create policy "Admins read customer orders"
on public.customer_orders for select to authenticated
using ((select public.is_store_admin()));

drop policy if exists "Admins update customer orders" on public.customer_orders;
create policy "Admins update customer orders"
on public.customer_orders for update to authenticated
using ((select public.is_store_admin()))
with check ((select public.is_store_admin()));

drop policy if exists "Admins read customer order items" on public.customer_order_items;
create policy "Admins read customer order items"
on public.customer_order_items for select to authenticated
using ((select public.is_store_admin()));

drop policy if exists "Admins read own membership" on public.store_admins;
create policy "Admins read own membership"
on public.store_admins for select to authenticated
using (user_id = (select auth.uid()));

-- The browser can read active products and submit orders only via the RPC.
-- No anonymous policy exposes customer orders or customer details.
grant select on public.cloud_fish_products to anon, authenticated;
grant insert, update, delete on public.cloud_fish_products to authenticated;
grant select, update on public.customer_orders to authenticated;
grant select on public.customer_order_items to authenticated;
grant select on public.store_admins to authenticated;

create or replace function public.place_customer_order(
  p_customer_name text,
  p_customer_phone text,
  p_pickup_at timestamptz,
  p_notes text,
  p_items jsonb
) returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_order_id uuid;
  v_order_code text;
  v_total numeric(12,2) := 0;
  v_item jsonb;
  v_product public.cloud_fish_products%rowtype;
  v_qty numeric(12,3);
  v_price numeric(12,2);
  v_product_id bigint;
begin
  if length(trim(coalesce(p_customer_name,''))) < 2 or length(trim(p_customer_name)) > 120 then
    raise exception 'يرجى إدخال اسم صحيح';
  end if;
  if length(regexp_replace(coalesce(p_customer_phone,''), '[^0-9+]', '', 'g')) not between 7 and 30 then
    raise exception 'يرجى إدخال رقم هاتف صحيح';
  end if;
  if p_pickup_at is null or p_pickup_at < now() then
    raise exception 'موعد الاستلام يجب أن يكون في المستقبل';
  end if;
  if length(coalesce(p_notes,'')) > 500 then
    raise exception 'الملاحظات طويلة جداً';
  end if;
  if jsonb_typeof(p_items) is distinct from 'array' or jsonb_array_length(p_items) < 1 or jsonb_array_length(p_items) > 30 then
    raise exception 'السلة غير صحيحة';
  end if;

  insert into public.customer_orders(customer_name, customer_phone, pickup_at, notes)
  values (trim(p_customer_name), trim(p_customer_phone), p_pickup_at, coalesce(trim(p_notes), ''))
  returning id, order_code into v_order_id, v_order_code;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    if coalesce(v_item->>'product_id','') !~ '^[0-9]{1,18}$' then
      raise exception 'أحد الأصناف غير صحيح';
    end if;
    v_product_id := (v_item->>'product_id')::bigint;
    select * into v_product
    from public.cloud_fish_products
    where id = v_product_id and is_active = true
    for share;

    if not found then
      raise exception 'أحد أصناف السمك لم يعد متاحاً';
    end if;
    if coalesce(v_item->>'quantity_kg','') !~ '^[0-9]+(\.[0-9]{1,3})?$' then
      raise exception 'الكمية غير صحيحة';
    end if;
    v_qty := (v_item->>'quantity_kg')::numeric;
    if v_qty <= 0 or v_qty > 100 then
      raise exception 'كمية غير صحيحة';
    end if;

    v_price := case when v_product.is_offer then v_product.offer_price_per_kg else v_product.price_per_kg end;
    insert into public.customer_order_items(order_id, product_id, fish_name, quantity_kg, unit_price, line_total)
    values (v_order_id, v_product.id, v_product.name, v_qty, v_price, round(v_qty * v_price, 2));
    v_total := v_total + round(v_qty * v_price, 2);
  end loop;

  update public.customer_orders set total = v_total where id = v_order_id;
  return jsonb_build_object('order_code', v_order_code, 'total', v_total, 'status', 'جديد');
end;
$$;

revoke all on function public.place_customer_order(text,text,timestamptz,text,jsonb) from public;
grant execute on function public.place_customer_order(text,text,timestamptz,text,jsonb) to anon, authenticated;
revoke all on function public.is_store_admin() from public;
grant execute on function public.is_store_admin() to anon, authenticated;

